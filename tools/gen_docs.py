"""Generate docs/presets_reference.md and docs/bindings.md from the code (so the docs cannot drift)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _pkg  # noqa: E402

_pkg.load()
from flowfx.core import presets  # noqa: E402

DOCS = _pkg.ROOT / "docs"
CATS = {"surface": "Surface (spectral and still water)", "flow": "Flow", "event": "Events"}


def fmt(v):
    if isinstance(v, float):
        return f"{v:.3g}"
    if isinstance(v, list):
        return " x ".join(fmt(x) for x in v)
    return str(v)


def presets_md():
    L = ["# Preset reference\n",
         "Generated by `tools/gen_docs.py` from `flowfx/presets/*/*.json`. Derived values come from `core/theory.py`.\n"]
    for cat, title in CATS.items():
        L.append(f"## {title}\n")
        L.append("| ID | Engine | Physical inputs | Derived | Description |\n|---|---|---|---|---|")
        for p in presets.load_all():
            if p["category"] != cat:
                continue
            phys = ", ".join(f"{k} {fmt(v)}" for k, v in p["physical"].items())
            tgt = ", ".join(f"{k} {fmt(v)}" for k, v in p.get("targets", {}).items())
            der = ", ".join(f"{k} {fmt(v)}" for k, v in presets.derive(p).items())
            L.append(f"| `{p['id']}` | {p['engine']} | {phys}{'; target ' + tgt if tgt else ''} | {der} | {p['description']} |")
        L.append("")
    return "\n".join(L)


def bindings_md():
    from flowfx.bindings import dynamic_paint, fluid, ocean

    L = ["# Blender API bindings\n",
         "Every Blender identifier FlowFX uses lives in `flowfx/bindings/`. `tests/api_contract/` asserts each row "
         "against the running Blender (verified on 5.2.2). Generated by `tools/gen_docs.py`.\n"]

    def table(title, contract):
        L.append(f"## {title}\n")
        L.append("| Identifier | RNA type | Default |\n|---|---|---|")
        for k, v in contract.items():
            t, d = v if isinstance(v, tuple) else (v, None)
            L.append(f"| `{k}` | {t} | {'' if d is None else d} |")
        L.append("")

    table("OceanModifier", ocean.CONTRACT)
    table("FluidDomainSettings", fluid.DOMAIN_CONTRACT)
    table("FluidFlowSettings", fluid.FLOW_CONTRACT)
    table("FluidEffectorSettings", fluid.EFFECTOR_CONTRACT)
    table("DynamicPaintSurface (wave)", dynamic_paint.WAVE_CONTRACT)
    L.append("## Operators\n")
    L.append("`bpy.ops.fluid.` " + ", ".join(f"`{n}`" for n in fluid.BAKE_OPERATORS) + "\n")
    return "\n".join(L)


if __name__ == "__main__":
    DOCS.mkdir(exist_ok=True)
    (DOCS / "presets_reference.md").write_text(presets_md(), encoding="utf-8")
    (DOCS / "bindings.md").write_text(bindings_md(), encoding="utf-8")
    print("wrote docs/presets_reference.md and docs/bindings.md")
